export function getKecamatanListForKota(kotaKabupaten: string): string[] {
  const mapped = KECAMATAN_DESA_MAP[kotaKabupaten];
  if (mapped) {
    return Object.keys(mapped);
  }
  const cleanName = kotaKabupaten
    .replace(/^Kota Administrasi\s+/i, '')
    .replace(/^Kabupaten Administrasi\s+/i, '')
    .replace(/^Kota\s+/i, '')
    .replace(/^Kabupaten\s+/i, '')
    .trim();

  return [
    `Kecamatan ${cleanName} Pusat`,
    `Kecamatan ${cleanName} Utara`,
    `Kecamatan ${cleanName} Selatan`,
    `Kecamatan ${cleanName} Timur`,
    `Kecamatan ${cleanName} Barat`,
  ];
}

export function getDesaKelurahanListForKecamatan(
  kotaKabupaten: string,
  kecamatan: string
): string[] {
  const mappedKota = KECAMATAN_DESA_MAP[kotaKabupaten];
  if (mappedKota && mappedKota[kecamatan]) {
    return mappedKota[kecamatan];
  }
  const cleanKec = kecamatan.replace(/^Kecamatan\s+/i, '').trim() || 'Utama';
  return [
    `Kelurahan ${cleanKec} I`,
    `Kelurahan ${cleanKec} II`,
    `Desa ${cleanKec} Jaya`,
    `Desa ${cleanKec} Makmur`,
    `Desa ${cleanKec} Baru`,
  ];
}
